-- Where the last successful poll got to. One row per sync stream.
CREATE TABLE sync_state (
    stream_name VARCHAR(50) PRIMARY KEY,
    watermark   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Idempotency: one row per order version already accepted by the ERP.
CREATE TABLE processed_orders (
    order_code    VARCHAR(100) NOT NULL,
    order_version INT          NOT NULL,
    erp_reference VARCHAR(100),
    processed_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (order_code, order_version)
);

-- Orders that could not be synced, with enough context to fix and replay them.
CREATE TABLE dead_letters (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_code    VARCHAR(100)  NOT NULL,
    order_version INT           NOT NULL,
    failure_type  VARCHAR(30)   NOT NULL,
    error_message VARCHAR(2000) NOT NULL,
    payload       TEXT          NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_dead_letters_order ON dead_letters (order_code, order_version);
